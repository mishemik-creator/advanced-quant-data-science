import numpy as np

# Задаем базовые априорные вероятности
p_btc_grows = 0.60         # P(A) - Биткоин растет
p_btc_falls = 1 - p_btc_grows # P(~A) - Биткоин падает

# Задаем условные вероятности (поведение китов)
p_whale_if_grows = 0.80    # P(B|A) - Кит перевел, если рынок растет
p_whale_if_falls = 0.30    # P(B|~A) - Кит перевел, если рынок падает

# 1. Формула полной вероятности: считаем общую вероятность события B P(B)
# (вероятность того, что кит переведет средства в любой случайный день)
p_whale_total = (p_whale_if_grows * p_btc_grows) + (p_whale_if_falls * p_btc_falls)

# 2. ТЕОРЕМА БАЙЕСА: вычисляем скорректированную вероятность P(A|B)
p_grows_given_whale = (p_whale_if_grows * p_btc_grows) / p_whale_total

print("="*60)
print("🧠 БАЙЕСОВСКИЙ ОБНОВЛЯЕМЫЙ АЛГОРИТМ ПРЕДСКАЗАНИЙ (DRW STYLE)")
print("="*60)
print(f"📊 Общая историческая вероятность активности китов P(B): {p_whale_total * 100:.2f}%")
print(f"🎯 Скорректированная вероятность роста BTC после фиксации кита P(A|B): {p_grows_given_whale * 100:.2f}%")
print("="*60)
