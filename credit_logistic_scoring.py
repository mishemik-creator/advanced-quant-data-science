import numpy as np

print("📐 Запуск Квант-Модуля Логистической Регрессии и Кредитного Скоринга...")

# 1. ЧИСТАЯ МАТЕМАТИКА: Реализуем функцию Сигмоиды вручную
def sigmoid(z):
    """
    Сигмоида: преобразует любое число в вероятность от 0.0 до 1.0
    """
    return 1 / (1 + np.exp(-z))

def predict_default_probability(health_factor, market_volatility):
    """
    Логистическая модель оценки рисков.
    Веса (weights) и сдвиг (bias) предопределены на основе исторического анализа СУБД:
    Чем выше Health Factor, тем НИЖЕ риск дефолта (отрицательный вес)
    Чем выше волатильность рынка, тем ВЫШЕ риск дефолта (положительный вес)
    """
    w_health = -3.5       # Высокое здоровье залога снижает риск
    w_vol = 5.2          # Высокая волатильность повышает риск
    bias = 1.2           # Базовый сдвиг модели
    
    # Считаем линейную комбинацию z
    z = (health_factor * w_health) + (market_volatility * w_vol) + bias
    
    # Пропускаем через Сигмоиду, чтобы получить ЧИСТУЮ вероятность дефолта
    prob = sigmoid(z)
    return prob

# Симулируем двух заемщиков текущих суток (19.10.2026)
# Заемщик 1: Высокий залог (Health Factor = 2.1), стабильный рынок (Волатильность = 15% -> 0.15)
prob_user_1 = predict_default_probability(health_factor=2.1, market_volatility=0.15)

# Заемщик 2: Критический залог (Health Factor = 1.1), штормовой рынок (Волатильность = 45% -> 0.45)
prob_user_2 = predict_default_probability(health_factor=1.1, market_volatility=0.45)

print("\n" + "="*60)
print("📊 РЕЗУЛЬТАТЫ ЛОГИСТИЧЕСКОГО АНАЛИЗА ДЕФОЛТОВ ПО СИГМОИДЕ")
print("="*60)
print(f"👤 ЗАЕМЩИК №1 (Надежный):")
print(f"📉 Математическая вероятность дефолта: {prob_user_1 * 100:.2f}%")
print(f"🛡️ Вердикт Банка: " + ("❌ ОТКАЗАТЬ В КРЕДИТЕ" if prob_user_1 > 0.15 else "✅ КРЕДИТ ОДОБРЕН"))
print("-"*60)
print(f"👤 ЗАЕМЩИК №2 (Рискованный):")
print(f"📉 Математическая вероятность дефолта: {prob_user_2 * 100:.2f}%")
print(f"🛡️ Вердикт Банка: " + ("❌ ОТКАЗАТЬ В КРЕДИТЕ" if prob_user_2 > 0.15 else "✅ КРЕДИТ ОДОБРЕН"))
print("="*60)
