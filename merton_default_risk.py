import numpy as np
from scipy import stats

print("📐 Запуск Квант-Модуля Оценки Рисков Протоколов по Структурной Модели Мертона...")

def calculate_merton_edf(V, D, T, r, sigma_V):
    """
    Вычисляет Расстояние до дефолта (DD) и Ожидаемую вероятность дефолта (EDF):
    DD = (ln(V / D) + (r - 0.5 * sigma_V^2) * T) / (sigma_V * sqrt(T))
    EDF = N(-DD)
    
    Где:
    V - Совокупная рыночная стоимость активов протокола (Value of Assets)
    D - Суммарный долг / обязательства протокола (Face Value of Debt)
    T - Срок до выплаты долга (в долях года)
    r - Безрисковая процентная ставка
    sigma_V - Волатильность стоимости активов протокола
    """
    # Вычисляем расстояние до дефолта (количество стандартных отклонений до точки банкротства)
    distance_to_default = (np.log(V / D) + (r - 0.5 * sigma_V ** 2) * T) / (sigma_V * np.sqrt(T))
    
    # Ожидаемая вероятность дефолта (хвост нормального распределения Гаусса)
    edf = stats.norm.cdf(-distance_to_default)
    
    return distance_to_default, edf

# Параметры крупного Web3-протокола на текущие сутки (19.10.2026)
assets_V = 500_000_000.00  # Стоимость активов в пулах: $500 млн USDT
debt_D = 420_000_000.00    # Обязательства перед вкладчиками: $420 млн USDT
T_horizon = 1.0            # Горизонт анализа - 1 год
r_free = 0.045             # Безрисковая ставка (4.5% годовых)
sigma_assets = 0.22        # Годовая волатильность активов пула (22%)

# Запускаем нобелевский риск-вычислитель
dd, edf = calculate_merton_edf(assets_V, debt_D, T_horizon, r_free, sigma_assets)

print("\n" + "="*60)
print("📊 РЕЗУЛЬТАТЫ СТРУКТУРНОГО АНАЛИЗА РИСКОВ ПО МОДЕЛИ МЕРТОНА")
print("="*60)
print(f"🏦 Объект анализа: Web3 Лендинговый Протокол (DeFi Pool)")
print(f"💰 Рыночная стоимость активов (V): ${assets_V:,.2f} USDT")
print(f"🧾 Объем обязательств / Долг (D): ${debt_D:,.2f} USDT")
print(f"🌪️ Волатильность активов пула (σ): {sigma_assets * 100:.2f}%")
print("-"*60)
print(f"📐 Расстояние до точки дефолта (DD): {dd:.4f} сигм")
print(f"\n🎯 ОЖИДАЕМАЯ ВЕРОЯТНОСТЬ ДЕФОЛТА (EDF): {edf * 100:.4f}%")
print("="*60)
print(f"🟢 СТАТУС НАДЕЖНОСТИ: " + ("⚠️ КРИТИЧЕСКИЙ РИСК" if edf > 0.05 else "✅ ВЫСОКАЯ СТАБИЛЬНОСТЬ"))
print("="*60)
