import numpy as np

# 1. Задаем матрицу переходных вероятностей P
# Строка 0 (текущий день - падение): [шанс остаться в падении, шанс вырасти]
# Строка 1 (текущий день - рост):   [шанс упасть, шанс продолжить рост]
P = np.array([
    [0.3, 0.7],  # Переходы из State 0 (Падение)
    [0.6, 0.4]   # Переходы из State 1 (Рост)
])

# 2. Задаем начальное состояние на сегодня: Биткоин упал (State 0)
# Вектор состояния: 100% шанс падения, 0% шанс роста
v_today = np.array([1.0, 0.0])

# Математическая магия Маркова: чтобы узнать вероятности через N дней,
# нужно умножить вектор состояния на матрицу переходов N раз!
v_tomorrow = np.dot(v_today, P)               # Вероятности на завтра (Шаг 1)
v_after_tomorrow = np.dot(v_tomorrow, P)      # Вероятности на послезавтра (Шаг 2)

# Стационарное (финальное) состояние рынка на бесконечной дистанции
# Считаем, к какому балансу сил рынок придет через 100 дней
P_100 = np.linalg.matrix_power(P, 100)
v_steady_state = np.dot(v_today, P_100)

print("="*60)
print("⛓️ МАРКОВСКОЕ МОДЕЛИРОВАНИЕ ВРЕМЕННЫХ РЯДОВ (QUANT STYLE)")
print("="*60)
print(f"🔮 Вероятности на завтра: Падение = {v_tomorrow[0]*100:.1f}%, Рост = {v_tomorrow[1]*100:.1f}%")
print(f"🎯 Вероятности на ПОСЛЕЗАВТРА: Падение = {v_after_tomorrow[0]*100:.1f}%, Рост = {v_after_tomorrow[1]*100:.1f}%")
print(f"🏛️ Стационарное состояние рынка на дистанции: Рост будет в {v_steady_state[1]*100:.2f}% всех дней")
print("="*60)
