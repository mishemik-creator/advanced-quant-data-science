import numpy as np
from scipy import stats

print("📐 Запуск Квант-Модуля Ценообразования Деривативов Блэка-Шоулза...")

def calculate_black_scholes_call(S, K, T, r, sigma):
    """
    Вычисляет теоретическую цену европейского Call-опциона:
    C = S * N(d1) - K * e^(-r*T) * N(d2)
    
    Где:
    S - Текущая цена базового актива
    K - Цена страйк (цена исполнения контракта)
    T - Время до экспирации (в долях года)
    r - Безрисковая процентная ставка
    sigma - Аннуализированная волатильность базового актива
    """
    # Рассчитываем промежуточные коэффициенты d1 и d2
    d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    
    # Применяем кумулятивную функцию нормального распределения Гаусса (SciPy)
    call_price = (S * stats.norm.cdf(d1)) - (K * np.exp(-r * T) * stats.norm.cdf(d2))
    return call_price, d1, d2

